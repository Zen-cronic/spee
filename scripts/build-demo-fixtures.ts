// Writes the SYNTHETIC demo fixtures (fixtures/demo/*.json) from src/hub/demoData.ts.
//   npm run demo:fixtures
// Deterministic: test/hub-demo.test.ts checks the committed files match a fresh build.
import { mkdirSync, writeFileSync } from "node:fs";
import { DEMO_CALENDAR, DEMO_DEFAULT_CYCLE, DEMO_EPOCH, DEMO_LABEL, DEMO_SCENARIOS, DEMO_WEARER, buildAttempts, buildDeck, buildPrereg, buildSessions } from "../src/hub/demoData.js";

export function demoFixtures(): Record<string, unknown> {
  const deck = buildDeck();
  const note = `${DEMO_LABEL}. Generated by npm run demo:fixtures from src/hub/demoData.ts.`;
  return {
    "sessions.json": { note, sessions: buildSessions() },
    "deck.json": { note, ...deck },
    "attempts.json": { note, attempts: buildAttempts(deck) },
    "prereg-transfer.json": buildPrereg(),
    "demo.json": { note, now: new Date(DEMO_EPOCH).toISOString(), wearer: DEMO_WEARER, calendar: DEMO_CALENDAR.map((e) => ({ title: e.title, startsAt: new Date(e.startsAt).toISOString() })), scenarios: DEMO_SCENARIOS, defaultCycle: DEMO_DEFAULT_CYCLE },
  };
}

if (process.argv[1]?.endsWith("build-demo-fixtures.ts")) {
  mkdirSync("fixtures/demo", { recursive: true });
  for (const [f, v] of Object.entries(demoFixtures())) writeFileSync(`fixtures/demo/${f}`, JSON.stringify(v, null, 1) + "\n");
  console.log(`Wrote ${Object.keys(demoFixtures()).length} files to fixtures/demo/`);
}
